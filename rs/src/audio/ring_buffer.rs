use std::{
    cell::UnsafeCell,
    mem::MaybeUninit,
    ptr,
    sync::atomic::{AtomicUsize, Ordering},
};

// ============================================================================
// Lock-free MPMC Ring Buffer
// ============================================================================
///
/// Lock-free кольцевой буфер с множеством производителей и множеством потребителей
/// (MPMC — Multiple Producers, Multiple Consumers).
///
/// Реализован на основе алгоритма с порядковыми номерами слотов (sequence-based),
/// аналогичного используемому в [`crossbeam::queue::ArrayQueue`].
/// Гарантирует:
/// - Отсутствие блокировок: операции `push` и `pop` выполняются за O(1) без мьютексов.
/// - Потокобезопасность: одновременные вызовы `push` из разных потоков и `pop` из разных
///   потоков корректны и не приводят к гонкам данных.
/// - Линеаризуемость операций.
///
/// Внутренняя ёмкость фиксирована и задаётся при создании. Для отличия пустого буфера
/// от полного используется классический приём с одним "служебным" слотом: максимальное
/// число хранимых элементов равно `capacity - 1`. Метод `is_full` возвращает `true`,
/// когда `capacity_remaining() <= 1`, т.е. когда остался 0 или 1 свободный слот.
///
/// # Пример
///
/// ```
/// let rb = RingBuffer::new(1024);
/// rb.push(vec![1,2,3]).unwrap();
/// assert_eq!(rb.pop(), Some(vec![1,2,3]));
/// ```
///
/// # Потокобезопасность
///
/// Тип реализует `Send` и `Sync`, поэтому буфер можно разделять между потоками
/// по ссылке (например, через `Arc`).

// ============================================================================
// Cache line padding
// ============================================================================

/// Вспомогательная обёртка, гарантирующая выравнивание на границу кэш-линии (64 байта).
/// Предотвращает ложное разделение (false sharing) счётчиков `head` и `tail`,
/// которые могут активно изменяться разными потоками.
#[repr(align(64))]
struct CachePadded<T>(T);

// ============================================================================
// Slot
// ============================================================================

/// Слот кольцевого буфера, хранящий порядковый номер и полезные данные.
///
/// `seq` отслеживает состояние слота:
/// - Если `seq` равен индексу слота (позиции в буфере), слот **свободен**.
/// - После успешной записи `seq` устанавливается в индекс + 1, сигнализируя,
///   что слот **заполнен**.
/// - После чтения `seq` увеличивается на `capacity`, снова делая слот **свободным**
///   для следующего цикла.
///
/// Такая схема позволяет различать состояния без дополнительных флагов, используя
/// естественное увеличение счётчиков.
///
/// `data` защищён `UnsafeCell` — доступ синхронизируется исключительно через `seq`
/// и атомарные операции с правильным упорядочением доступа к памяти.
struct Slot {
    seq: AtomicUsize,
    data: UnsafeCell<MaybeUninit<Vec<u8>>>,
}

// Реализуем Send и Sync вручную, так как UnsafeCell не является Sync по умолчанию.
// Это безопасно, потому что доступ к данным полностью контролируется протоколом
// атомарного seq.
unsafe impl Send for Slot {}
unsafe impl Sync for Slot {}

// ============================================================================
// RingBuffer
// ============================================================================

/// Lock-free MPMC кольцевой буфер фиксированной ёмкости.
pub struct RingBuffer {
    /// Массив слотов, размещённый в куче (boxed slice для неизменяемого размера).
    buffer: Box<[Slot]>,
    /// Ёмкость буфера (количество слотов).
    capacity: usize,

    /// Позиция для следующей вставки (head). Разделена кэш-линией с tail.
    head: CachePadded<AtomicUsize>,
    /// Позиция для следующего извлечения (tail). Разделена кэш-линией с head.
    tail: CachePadded<AtomicUsize>,
}

// Буфер можно безопасно передавать и делить между потоками.
unsafe impl Send for RingBuffer {}
unsafe impl Sync for RingBuffer {}

impl RingBuffer {
    // =========================================================================
    // Конструктор
    // =========================================================================

    /// Создаёт новый кольцевой буфер с заданной ёмкостью.
    ///
    /// Фактическое максимальное количество элементов, которые можно хранить
    /// одновременно, равно `capacity - 1`.
    ///
    /// # Паника
    ///
    /// Паникует, если `capacity == 0`.
    pub fn new(capacity: usize) -> Self {
        assert!(capacity > 0);

        // Инициализируем слоты: начальное значение seq = индекс слота,
        // data — неинициализированная память (MaybeUninit).
        let mut vec = Vec::with_capacity(capacity);
        for i in 0..capacity {
            vec.push(Slot {
                seq: AtomicUsize::new(i),
                data: UnsafeCell::new(MaybeUninit::uninit()),
            });
        }

        Self {
            buffer: vec.into_boxed_slice(),
            capacity,
            head: CachePadded(AtomicUsize::new(0)),
            tail: CachePadded(AtomicUsize::new(0)),
        }
    }

    // =========================================================================
    // Вставка (push)
    // =========================================================================

    /// Пытается поместить значение в буфер.
    ///
    /// Возвращает `Ok(())` при успешной вставке. Если буфер заполнен (нет свободных
    /// слотов для записи), возвращает `Err(value)` с исходным значением.
    ///
    /// Алгоритм:
    /// 1. Читаем текущий `head` (relaxed, так как точное значение будет подтверждено
    ///    через seq слота).
    /// 2. Получаем слот по индексу `pos % capacity` и его `seq` (acquire).
    /// 3. Если `seq == pos`, слот свободен — пытаемся атомарно инкрементировать `head`
    ///    (CAS). При успехе записываем данные и устанавливаем `seq = pos + 1` (release),
    ///    делая слот доступным для потребителя.
    /// 4. Если `seq < pos`, буфер полон — возвращаем ошибку.
    /// 5. Если `seq > pos`, другой производитель уже занял этот слот — обновляем `pos`
    ///    и повторяем.
    ///
    /// Используется упорядочение:
    /// - `Acquire` при чтении `seq`, чтобы видеть все записи производителя,
    ///   который заполнил этот слот.
    /// - `Release` при записи нового `seq`, чтобы все данные стали видны потребителю.
    pub fn push(&self, value: Vec<u8>) -> Result<(), Vec<u8>> {
        let mut pos = self.head.0.load(Ordering::Relaxed);

        loop {
            let slot = &self.buffer[pos % self.capacity];
            let seq = slot.seq.load(Ordering::Acquire);

            let diff = seq as isize - pos as isize;

            if diff == 0 {
                // Слот свободен — пытаемся зарезервировать позицию.
                match self.head.0.compare_exchange_weak(
                    pos,
                    pos + 1,
                    Ordering::Relaxed,
                    Ordering::Relaxed,
                ) {
                    Ok(_) => {
                        // Записываем данные в слот.
                        unsafe {
                            let ptr = (*slot.data.get()).as_mut_ptr();
                            ptr::write(ptr, value);
                        }
                        // Сообщаем потребителям, что слот готов.
                        slot.seq.store(pos + 1, Ordering::Release);
                        return Ok(());
                    }
                    // Другой поток изменил head — обновляем pos и пробуем снова.
                    Err(p) => pos = p,
                }
            } else if diff < 0 {
                // Буфер полон (seq отстаёт от pos).
                return Err(value);
            } else {
                // Другой производитель уже сдвинул head вперёд, обновляем pos.
                pos = self.head.0.load(Ordering::Relaxed);
            }
        }
    }

    /// Добавляет элемент в **начало** очереди (push_front)
    /// Используется при неудачной отправке, чтобы вернуть пакет обратно
    pub fn push_front(&self, value: Vec<u8>) -> Result<(), Vec<u8>> {
        let mut head = self.head.0.load(Ordering::Relaxed);

        loop {
            let slot = &self.buffer[head % self.capacity];
            let seq = slot.seq.load(Ordering::Acquire);

            // head должен указывать на свободный слот для записи "слева"
            if seq == head.wrapping_add(1) {
                // Можно писать в начало
                let next_head = head.wrapping_sub(1);

                if self.head.0.compare_exchange_weak(
                    head,
                    next_head,
                    Ordering::Release,
                    Ordering::Relaxed,
                ).is_ok() {
                    unsafe {
                        (*slot.data.get()).write(value);
                    }
                    slot.seq.store(next_head, Ordering::Release);
                    return Ok(());
                }
                // CAS не удался — retry
            } else if seq == head {
                // Буфер пуст (или кто-то уже двигает head)
                head = self.head.0.load(Ordering::Relaxed);
            } else {
                // Буфер полон (или race condition)
                return Err(value);
            }
        }
    }

    // =========================================================================
    // Извлечение (pop)
    // =========================================================================

    /// Пытается извлечь значение из буфера.
    ///
    /// Возвращает `Some(value)`, если буфер не пуст, или `None`, если данных нет.
    ///
    /// Алгоритм:
    /// 1. Читаем `tail` (relaxed).
    /// 2. Слот по индексу `pos % capacity`; читаем его `seq` (acquire).
    /// 3. Если `seq == pos + 1`, слот заполнен — пытаемся атомарно инкрементировать `tail`
    ///    (CAS). При успехе читаем данные и устанавливаем `seq = pos + capacity` (release),
    ///    возвращая слот в свободное состояние для следующего цикла.
    /// 4. Если `seq < pos + 1`, буфер пуст — возвращаем `None`.
    /// 5. Если `seq > pos + 1`, другой потребитель уже забрал этот слот — обновляем `pos`.
    ///
    /// Упорядочение аналогично `push`: Acquire при чтении seq, чтобы видеть записанные
    /// данные, и Release при освобождении слота.
    pub fn pop(&self) -> Option<Vec<u8>> {
        let mut pos = self.tail.0.load(Ordering::Relaxed);

        loop {
            let slot = &self.buffer[pos % self.capacity];
            let seq = slot.seq.load(Ordering::Acquire);

            let diff = seq as isize - (pos as isize + 1);

            if diff == 0 {
                // Слот заполнен — пытаемся застолбить позицию для чтения.
                match self.tail.0.compare_exchange_weak(
                    pos,
                    pos + 1,
                    Ordering::Relaxed,
                    Ordering::Relaxed,
                ) {
                    Ok(_) => {
                        // Читаем данные (unsafe: синхронизация через seq гарантирует,
                        // что инициализация завершена и гонок нет).
                        let value = unsafe {
                            let ptr = (*slot.data.get()).as_ptr();
                            ptr::read(ptr)
                        };
                        // Освобождаем слот для нового использования.
                        slot.seq.store(pos + self.capacity, Ordering::Release);
                        return Some(value);
                    }
                    Err(p) => pos = p,
                }
            } else if diff < 0 {
                // Буфер пуст.
                return None;
            } else {
                // Другой потребитель уже ушёл вперёд.
                pos = self.tail.0.load(Ordering::Relaxed);
            }
        }
    }

    // =========================================================================
    // Информационные методы (семантика корректна для MPMC)
    // =========================================================================

    /// Возвращает количество элементов, находящихся в буфере в данный момент.
    ///
    /// Так как буфер используется многими потоками, результат может устареть
    /// сразу после вызова. Используйте для приблизительных оценок.
    pub fn len(&self) -> usize {
        let head = self.head.0.load(Ordering::Acquire);
        let tail = self.tail.0.load(Ordering::Acquire);
        head.saturating_sub(tail)
    }

    /// Возвращает `true`, если буфер не содержит ни одного элемента.
    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    /// Возвращает количество свободных слотов, доступных для записи.
    ///
    /// С учётом служебного слота реальное количество возможных вставок может быть
    /// на 1 меньше этого числа, если буфер почти полон.
    pub fn capacity_remaining(&self) -> usize {
        self.capacity - self.len().min(self.capacity)
    }

    /// Возвращает `true`, если буфер заполнен (не может принять новые элементы без
    /// предварительного извлечения).
    ///
    /// Из-за резервирования одного слота для индикации заполнения, метод возвращает
    /// `true`, когда `capacity_remaining() <= 1`.
    pub fn is_full(&self) -> bool {
        self.capacity_remaining() <= 1
    }

    // =========================================================================
    // Снимок состояния (не линеаризуемо, но безопасно)
    // =========================================================================

    /// Возвращает копию элемента по логическому индексу (0 — самый старый элемент
    /// в буфере, 1 — следующий, и т.д.).
    ///
    /// **Важно:** Этот метод не линеаризуем относительно параллельных `push`/`pop`.
    /// Полученная копия может относиться к элементу, который уже извлечён или
    /// перезаписан. Используйте только в ситуациях, где согласованность не критична
    /// (например, для отладки или статистики).
    ///
    /// Возвращает `None`, если `index` выходит за пределы текущего количества элементов.
    pub fn get_clone_at(&self, index: usize) -> Option<Vec<u8>> {
        let tail = self.tail.0.load(Ordering::Acquire);
        let head = self.head.0.load(Ordering::Acquire);

        let len = head.saturating_sub(tail);
        if index >= len {
            return None;
        }

        let pos = (tail + index) % self.capacity;
        let slot = &self.buffer[pos];

        // Безопасность: мы не можем гарантировать, что слот всё ещё содержит валидные
        // данные (из-за параллельных pop), но чтение не вызовет неопределённого поведения,
        // так как Vec<u8> всегда остаётся корректным значением в памяти.
        unsafe {
            let ptr = (*slot.data.get()).as_ptr();
            Some((*ptr).clone())
        }
    }

    // =========================================================================
    // Очистка
    // =========================================================================

    /// Очищает буфер, извлекая все элементы через `pop()`.
    ///
    /// Использование `pop` гарантирует корректность в многопоточном окружении:
    /// другие потоки, одновременно вызывающие `pop` или `push`, увидят согласованное
    /// состояние. Простой обход слотов вразрез с протоколом `seq` невозможен.
    ///
    /// После возврата буфер пуст (`is_empty() == true`), если только параллельные
    /// вставки не добавили новые элементы в процессе очистки.
    pub fn clear(&self) {
        // Нельзя итерировать слоты напрямую из-за MPMC семантики.
        // Вместо этого безопасно осушаем буфер штатным методом.
        while self.pop().is_some() {}
    }
}

// =============================================================================
// Деструктор
// =============================================================================

/// При удалении буфера все оставшиеся элементы корректно извлекаются и дропаются,
/// предотвращая утечки памяти.
impl Drop for RingBuffer {
    fn drop(&mut self) {
        // Вызываем pop для каждого оставшегося элемента; он же освободит память Vec.
        while self.pop().is_some() {}
    }
}