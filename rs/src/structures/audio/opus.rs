/// Opus frame тишины (Silent Frame).
///
/// Используется для поддержания аудиопотока при отсутствии реального звука,
/// когда трек поставлен на паузу или между треками есть пауза.
/// Позволяет не разрывать RTP-поток и сохранять непрерывность sequence/timestamp.
pub const SILENT_FRAME: [u8; 3] = [0xf8, 0xff, 0xfe]; // 0xFC