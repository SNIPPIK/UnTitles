use std::fmt;

/// Максимальное количество Opus-фреймов, которое может содержаться
/// в одном Opus-пакете.
///
/// Значение соответствует ограничениям формата Opus, описанным в
/// RFC 6716. Оно используется как верхняя граница при разборе
/// структуры пакета и не позволяет парсеру принять заведомо
/// некорректное количество кадров.
///
/// Важно: это ограничение относится именно к количеству кадров
/// внутри одного Opus-пакета, а не к количеству RTP-пакетов.
pub const MAX_OPUS_FRAMES: usize = 5;

/// Максимальный размер одного Opus-фрейма в байтах.
///
/// Согласно RFC 6716, один Opus frame не может превышать 1275 байт.
/// Значение используется парсером как защитная граница при разборе
/// размеров отдельных кадров.
///
/// Превышение этого значения означает, что структура пакета
/// некорректна независимо от того, насколько велик общий payload.
pub const MAX_OPUS_FRAME_BYTES: usize = 1275;

/// TOC (Table Of Contents) байт Opus-пакета.
///
/// Первый байт каждого Opus-пакета содержит компактное описание
/// последующей структуры пакета:
///
/// ```text
///  7 6 5 4 3 | 2 | 1 0
/// +-----------+---+-----+
/// |   config  | S |  C  |
/// +-----------+---+-----+
/// ```
///
/// * `config` — 5 бит, определяющих режим кодека и длительность кадра.
/// * `stereo` — 1 бит, указывающий наличие стерео.
/// * `frame_code` — 2 бита, определяющих схему расположения кадров.
///
/// Формат соответствует структуре TOC, определённой RFC 6716 §3.1.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OpusToc {
    /// Значение `config` из старших пяти бит TOC.
    ///
    /// Диапазон: `0..=31`.
    ///
    /// В зависимости от диапазона значение определяет используемый
    /// режим Opus и длительность одного аудио-кадра.
    pub config: u8,

    /// Stereo flag из TOC.
    ///
    /// `false` — mono.
    /// `true`  — stereo.
    ///
    /// Сам флаг не изменяет структуру packet framing, но описывает
    /// количество каналов аудиоданных, закодированных в кадре.
    pub stereo: bool,

    /// Frame Code из младших двух бит TOC.
    ///
    /// Значение определяет способ упаковки одного или нескольких
    /// Opus-фреймов внутри текущего пакета:
    ///
    /// * `0` — один фрейм;
    /// * `1` — два фрейма CBR;
    /// * `2` — два фрейма VBR;
    /// * `3` — несколько фреймов, количество которых задаётся
    ///   дополнительным полем внутри пакета.
    pub frame_code: u8,
}

impl OpusToc {
    /// Разбирает сырой TOC-байт на отдельные логические поля.
    ///
    /// Никаких проверок здесь не требуется: любой `u8` имеет
    /// корректное битовое представление TOC.
    ///
    /// # Аргументы
    ///
    /// * `byte` — первый байт Opus-пакета.
    ///
    /// # Возвращает
    ///
    /// [`OpusToc`] с отдельно извлечёнными `config`, `stereo`
    /// и `frame_code`.
    #[inline]
    pub fn parse(byte: u8) -> Self {
        Self {
            // Биты 7..=3 содержат configuration index.
            //
            // Сдвигаем значение вправо на 3 позиции, после чего
            // маскируем пятью единицами, чтобы гарантированно
            // оставить только диапазон 0..=31.
            config: (byte >> 3) & 0x1F,

            // Бит 2 содержит stereo flag.
            //
            // После сдвига значение равно 0 или 1, поэтому
            // сравнение с нулём напрямую преобразует его в bool.
            stereo: (byte >> 2) & 1 != 0,

            // Биты 1..=0 содержат frame code.
            frame_code: byte & 0b11,
        }
    }
}

/// Структурная информация о разобранном Opus-пакете.
///
/// Эта структура не содержит сами аудиоданные. Она представляет
/// только результат структурного анализа packet framing и позволяет
/// следующему уровню обработчика работать с уже вычисленными
/// границами.
///
/// Такой подход позволяет отделить:
///
/// ```text
/// raw bytes
///     ↓
/// packet parser
///     ↓
/// OpusPacketInfo
///     ↓
/// frame extraction / RTP / player
/// ```
///
/// от непосредственного хранения или декодирования аудио.
#[derive(Debug, Clone, Copy)]
pub struct OpusPacketInfo {
    /// Разобранный TOC-байт.
    ///
    /// Содержит configuration, stereo flag и frame code.
    //pub toc: OpusToc,

    /// Количество Opus-фреймов в текущем пакете.
    ///
    /// Значение уже учитывает `frame_code` и, если необходимо,
    /// дополнительное поле количества кадров.
    //pub frame_count: usize,

    /// Размер padding в байтах.
    ///
    /// Padding находится в конце packet payload и не относится
    /// к аудиоданным. Это значение позволяет отделить padding
    /// от фактического frame payload без повторного разбора.
    //pub padding_bytes: usize,

    /// Количество байт, занимаемых непосредственно Opus-фреймами.
    ///
    /// Не включает TOC, framing metadata и padding.
    //pub payload_bytes: usize,

    /// Флаг Variable Bit Rate.
    ///
    /// `true` означает, что размеры отдельных кадров могут
    /// отличаться и должны определяться из length-полей.
    ///
    /// `false` означает CBR-структуру, где размер кадров
    /// определяется равномерным распределением payload.
    pub vbr: bool,
}

/// Реализация стандартного Rust `Error`.
///
/// Благодаря этому `OpusPacketError` можно напрямую использовать
/// в `Result<T, OpusPacketError>` и передавать через стандартные
/// механизмы обработки ошибок Rust.
impl std::error::Error for OpusPacketError {}

/// Человекочитаемое описание ошибки разбора Opus-пакета.
///
/// Сообщения намеренно содержат числовые значения, полученные
/// непосредственно из повреждённого пакета. Это существенно
/// упрощает диагностику malformed packets без необходимости
/// отдельно логировать внутреннее состояние парсера.
impl fmt::Display for OpusPacketError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            // Пакет не содержит ни одного байта.
            Self::Empty => write!(f, "empty packet"),

            // Размер входного пакета превышает установленный
            // MAX_OPUS_PACKET_BYTES.
            Self::TooLarge(n) => write!(f, "packet {} exceeds limit", n),

            // Входной buffer недостаточен даже для обязательной
            // начальной структуры пакета.
            Self::TruncatedHeader => write!(f, "truncated header"),

            // Количество кадров не соответствует допустимому
            // диапазону Opus packet framing.
            Self::InvalidFrameCount(n) => write!(f, "invalid frame count {}", n),

            // Length field содержит недопустимое значение.
            Self::InvalidLengthField => write!(f, "invalid size frame"),

            // Buffer закончился до того, как length field был
            // полностью прочитан.
            Self::TruncatedLengthField => write!(f, "truncated length field"),

            // Оставшегося payload недостаточно даже для минимального
            // размещения указанного количества кадров.
            Self::PayloadTooShort { payload, frames } => write!(
                f,
                "payload {} too short for {} frames",
                payload,
                frames
            ),

            // Для CBR размер payload должен быть равномерно
            // распределим между всеми кадрами.
            Self::PayloadNotDivisible { payload, frames } => write!(
                f,
                "payload {} not divisible by {} frames",
                payload,
                frames
            ),

            // Получен размер кадра, который не соответствует
            // ожидаемым ограничениям packet framing.
            Self::InvalidFrameSize(n) => write!(
                f,
                "invalid frame size {}",
                n
            ),

            // Рассчитанный размер payload отличается от фактического.
            //
            // Обычно означает ошибку в структурном разборе,
            // некорректное length field или повреждённый пакет.
            Self::PayloadMismatch { expected, actual } => write!(
                f,
                "payload mismatch: expected {}, actual {}",
                expected,
                actual
            )
        }
    }
}

/// Причина, по которой Opus-пакет не прошёл структурную валидацию.
///
/// Ошибки здесь относятся именно к **packet framing**.
///
/// Они не означают, что Opus-декодер обязательно не сможет
/// обработать данные. Парсер работает уровнем ниже: он сначала
/// проверяет, что входные bytes вообще имеют согласованную
/// структуру Opus-пакета.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OpusPacketError {
    /// Входной buffer не содержит ни одного байта.
    ///
    /// Без TOC невозможно определить даже базовую структуру пакета.
    Empty,

    /// Полный пакет превышает внутренний защитный лимит.
    ///
    /// Содержит фактический размер входного buffer.
    TooLarge(usize),

    /// В пакете недостаточно данных для чтения обязательного
    /// заголовка или TOC.
    TruncatedHeader,

    /// Количество кадров не соответствует допустимой структуре
    /// Opus packet framing.
    ///
    /// Содержит фактическое значение, извлечённое из пакета.
    InvalidFrameCount(u8),

    /// Payload слишком мал для указанного количества кадров.
    ///
    /// Даже минимальный допустимый frame требует хотя бы одного
    /// байта данных.
    PayloadTooShort {
        /// Фактически доступный payload.
        payload: usize,

        /// Количество кадров, которое необходимо разместить.
        frames: usize,
    },

    /// Для CBR размер payload невозможно равномерно распределить
    /// между указанным количеством кадров.
    PayloadNotDivisible {
        /// Размер payload после исключения служебных данных.
        payload: usize,

        /// Количество кадров.
        frames: usize,
    },

    /// Length field имеет некорректное значение или структуру.
    ///
    /// Используется, когда поле технически прочитано, но его
    /// содержимое не может быть принято как корректный размер.
    InvalidLengthField,

    /// Входной buffer закончился до полного чтения length field.
    ///
    /// В отличие от `InvalidLengthField`, здесь проблема именно
    /// в недостатке входных данных.
    TruncatedLengthField,

    /// Рассчитанный размер конкретного кадра не соответствует
    /// допустимым ограничениям.
    InvalidFrameSize(usize),

    /// Внутренний расчёт payload не совпал с фактическим размером.
    ///
    /// Это сильный сигнал о повреждении packet framing или ошибке
    /// в реализации самого парсера.
    PayloadMismatch {
        /// Размер, который должен был получиться.
        expected: usize,

        /// Размер, реально обнаруженный в packet.
        actual: usize,
    }
}