/**
 * Стандартные методы, вызываемые при удалении элемента из коллекции.
 * Вызываются последовательно в указанном порядке.
 *
 * - `disconnect` — отключение от внешних ресурсов (сеть, БД).
 * - `cleanup` — освобождение внутренних ресурсов (таймеры, буферы).
 * - `destroy` — финальное уничтожение объекта.
 */
const DEFAULT_METHODS = ["disconnect", "cleanup", "destroy"] as const;

/**
 * Методы, вызываемые при "тихом" удалении (без побочных эффектов, таких как
 * оповещение внешних систем или эмиссия событий).
 */
const SILENT_METHODS = ["silent_destroy"] as const;

/**
 * @author SNIPPIK
 * @description Типизированная коллекция для хранения объектов по ключу с
 * расширенным набором возможностей: ленивый кэш массива, встроенный вызов
 * методов жизненного цикла при удалении, поддержка идемпотентной вставки
 * и O(1)-операции.
 *
 * **Улучшения по сравнению с базовой версией:**
 * - Кэш массива `_arrayCache` обновляется лениво и сбрасывается только при
 *   модификации коллекции, что делает повторное получение `.array` O(1)
 *   вместо O(n).
 * - Метод `values()` возвращает нативный итератор `Map.values()`, позволяя
 *   обходить элементы без создания временного массива (полезно для больших
 *   коллекций или в горячих путях).
 * - Все операции вставки, удаления, поиска выполняются за O(1).
 *
 * @class Collection
 * @typeParam K - Тип хранимых объектов.
 * @typeParam T - Тип ключа (ID), по умолчанию `string`.
 * @public
 */
export class Collection<K, T = string> {
    /**
     * Внутреннее хранилище: ключ → объект.
     * `Map` гарантирует O(1) доступ, вставку и удаление, а также сохраняет
     * порядок вставки (что важно для итераторов).
     */
    private readonly _map = new Map<T, K>();

    /**
     * Кэш массива всех значений коллекции.
     * `null` означает, что кэш ещё не был создан или был сброшен.
     * Заполняется при первом обращении к геттеру `array` после модификации.
     */
    private _arrayCache: K[] | null = null;

    /**
     * Флаг "грязного" состояния кэша массива.
     * Устанавливается в `true` при любом изменении состава коллекции
     * (добавление, удаление, очистка). При следующем доступе к `.array`
     * кэш будет перестроен.
     */
    private _arrayDirty = true;

    /**
     * Возвращает массив всех значений коллекции.
     *
     * При первом обращении после изменения коллекции или сброса кэша
     * создаёт новый массив через spread-оператор (оптимизирован в V8).
     * При последующих вызовах возвращает закэшированный массив за O(1).
     *
     * **Важно:** Возвращаемый массив является живым снимком на момент
     * построения кэша. Если после этого коллекция изменится, массив
     * останется прежним до следующего обращения.
     */
    public get array(): K[] {
        if (this._arrayDirty) {
            // Spread быстрее Array.from в большинстве движков
            this._arrayCache = [...this._map.values()];
            this._arrayDirty = false;
        }
        
        return this._arrayCache!;
    };

    /**
     * Текущее количество элементов в коллекции (всегда актуально).
     * Сложность O(1) — прямой доступ к `Map.size`.
     */
    public get size(): number {
        return this._map.size;
    };

    /**
     * Возвращает объект по ключу или `undefined`, если ключ отсутствует.
     * Сложность O(1).
     *
     * @param ID - Ключ (идентификатор) объекта.
     */
    public get(ID: T): K | undefined {
        return this._map.get(ID);
    };

    /**
     * Добавляет объект в коллекцию с заданным ключом.
     *
     * **Идемпотентность:** если ключ `ID` уже существует, переданный
     * `value` **игнорируется**, и метод возвращает уже существующий объект.
     * Это предотвращает случайную перезапись и гарантирует, что объект
     * с данным ключом будет создан ровно один раз.
     *
     * **Инициализация:** колбэк `init` вызывается **только** при первой
     * вставке (до фактического сохранения в `Map`). Удобен для подписок,
     * открытия соединений и другой логики, которую нужно выполнить один раз.
     *
     * @param ID    - Уникальный ключ.
     * @param value - Объект для сохранения.
     * @param init  - Необязательный колбэк инициализации (принимает `value`).
     *
     * @returns Сохранённый объект (либо новый, либо ранее существовавший).
     */
    public set(ID: T, value: K, init?: (item: K) => void): K {
        const existing = this._map.get(ID);
        if (existing !== undefined) return existing;

        // Новый элемент: инициализируем (если задан колбэк), сохраняем,
        // помечаем кэш как неактуальный.
        init?.(value);
        this._map.set(ID, value);
        this._arrayDirty = true;
        return value;
    };

    /**
     * Удаляет объект по ключу с вызовом методов жизненного цикла.
     *
     * Порядок вызова методов зависит от параметра `silent`:
     * - **Обычный режим** (`silent = false`): последовательно вызываются
     *   `disconnect`, `cleanup`, `destroy` (если они определены).
     * - **Тихий режим** (`silent = true`): вызывается только `silent_destroy`.
     *
     * Методы вызываются только если они существуют и являются функциями.
     * После вызова методов объект удаляется из `Map`. Кэш массива сбрасывается.
     *
     * @param ID     - Ключ удаляемого объекта.
     * @param silent - Флаг "тихого" удаления (без лишних оповещений).
     *
     * @returns `true`, если объект был успешно удалён, иначе `false` (ключа нет).
     */
    public remove(ID: T, silent = false): boolean {
        const item = this._map.get(ID);
        if (item === undefined) return false;

        this._map.delete(ID);
        this._arrayDirty = true;

        // Выбираем набор методов жизненного цикла.
        const methods = silent ? SILENT_METHODS : DEFAULT_METHODS;

        // Последовательно вызываем каждый метод, если он существует.
        for (let i = 0; i < methods.length; i++) {
            const fn = (item as any)[methods[i]];

            if (typeof fn === "function") {
                fn.call(item);
            }
        }

        return true;
    };

    /**
     * Проверяет наличие объекта с указанным ключом.
     * Сложность O(1).
     */
    public has(ID: T): boolean {
        return this._map.has(ID);
    };

    /**
     * Полностью очищает коллекцию **без вызова** методов жизненного цикла.
     *
     * Если требуется корректное завершение объектов (disconnect/destroy),
     * необходимо предварительно вызвать `remove` для каждого элемента.
     * Кэш массива сбрасывается в `null`, флаг `_arrayDirty` устанавливается.
     */
    public clear(): void {
        this._map.clear();
        this._arrayCache = null;
        this._arrayDirty = true;
    };

    /**
     * Возвращает нативный итератор по значениям коллекции.
     *
     * В отличие от геттера `array`, **не создаёт** временный массив,
     * что позволяет эффективно обходить коллекцию в цикле `for..of`
     * без лишнего расхода памяти и времени.
     *
     * @returns Итератор по значениям в порядке вставки.
     *
     * @example
     * ```ts
     * for (const item of collection.values()) {
     *   process(item);
     * }
     * ```
     */
    public values(): IterableIterator<K> {
        return this._map.values();
    };
}