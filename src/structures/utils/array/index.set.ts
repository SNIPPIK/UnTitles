/**
 * Гибридная коллекция, объединяющая свойства множества (`Set`) и массива.
 *
 * Обеспечивает:
 * - **O(1)** добавление, удаление и проверку наличия элемента.
 * - **O(1)** получение элемента без предиката.
 * - Стабильный порядок итерации (порядок добавления), который, однако,
 *   **нарушается при удалении** элементов из-за оптимизации `swap-remove`.
 * - Быстрый доступ к внутреннему массиву для чтения.
 * - Безопасную итерацию через копию (`values()`).
 * - Итератор `[Symbol.iterator]`, работающий напрямую с внутренним массивом
 *   (быстрее, но небезопасен при параллельном изменении).
 *
 * **Потокобезопасность**: класс не является потокобезопасным и предназначен
 * для использования в однопоточном окружении (основной поток JS / один воркер).
 *
 * @typeParam T - Тип элементов коллекции.
 */
export class SetArray<T> {
    /**
     * Внутренний массив элементов.
     * Порядок соответствует очерёдности добавления, но может нарушаться
     * при удалении (`swap-remove`).
     *
     * @private
     */
    private _array: T[] = [];

    /**
     * Хеш-таблица: ключ — элемент, значение — его индекс в `_array`.
     * Позволяет получать индекс за O(1), что критично для быстрого удаления.
     *
     * @private
     */
    private _indexMap = new Map<T, number>();

    /**
     * Доступ к внутреннему массиву только для чтения.
     *
     * Геттер в V8, поэтому вызов `set.array` практически
     * не добавляет накладных расходов. Возвращаемый массив **не копируется**,
     * поэтому его изменение напрямую сломает инварианты коллекции.
     *
     * @returns Массив элементов на момент вызова.
     * @readonly
     */
    public get array(): readonly T[] {
        return this._array;
    };

    /**
     * Добавляет элемент в коллекцию.
     *
     * Если элемент уже существует, метод игнорирует его и возвращает `this`.
     * Амортизированная сложность: **O(1)** (за счёт `Map.set` и `Array.push`).
     *
     * @param item - Добавляемый элемент.
     * @returns `this` для цепочечных вызовов.
     *
     * @example
     * ```ts
     * set.add("first").add("second");
     * ```
     */
    public add(item: T): this {
        // Проверяем наличие через Map (O(1)).
        if (this._indexMap.has(item)) return this;

        const index = this._array.length;
        this._array.push(item);
        this._indexMap.set(item, index);
        return this;
    };

    /**
     * Проверяет, содержится ли элемент в коллекции.
     * Сложность: **O(1)**.
     *
     * @param item - Проверяемый элемент.
     * @returns `true`, если элемент присутствует, иначе `false`.
     */
    public has(item: T): boolean {
        return this._indexMap.has(item);
    };

    /**
     * Удаляет элемент из коллекции.
     *
     * Использует **swap-remove**: на место удаляемого элемента перемещается
     * последний элемент массива, после чего массив укорачивается на 1.
     * Это даёт O(1) вместо O(n), но **не сохраняет порядок** элементов.
     *
     * @param item - Удаляемый элемент.
     * @returns `true`, если элемент был удалён, иначе `false`.
     */
    public delete(item: T): boolean {
        const index = this._indexMap.get(item);
        if (index === undefined) return false;

        const lastIndex = this._array.length - 1;

        // Если удаляемый элемент не последний — меняем его с последним.
        if (index !== lastIndex) {
            const lastItem = this._array[lastIndex];
            this._array[index] = lastItem;
            // Обновляем индекс перемещённого элемента в Map.
            this._indexMap.set(lastItem, index);
        }

        // Удаляем последний элемент (pop быстрее, чем декремент length).
        this._array.pop();
        this._indexMap.delete(item);
        return true;
    };

    /**
     * Возвращает копию массива элементов.
     *
     * Безопасна для итерации при возможном изменении коллекции,
     * так как возвращается снимок на момент вызова.
     * В большинстве JS-движков `slice()` быстрее, чем spread-оператор.
     *
     * @returns Копия массива всех элементов.
     */
    public values(): T[] {
        return this._array.slice();
    };

    /**
     * Итератор по элементам коллекции **без копирования**.
     *
     * Работает напрямую с внутренним массивом, что даёт прирост
     * производительности по сравнению с `values()`. Однако **небезопасен**
     * при параллельном изменении коллекции (добавление/удаление во время
     * итерации приведёт к непредсказуемому поведению).
     *
     * @returns Итератор по внутреннему массиву.
     *
     * @example
     * ```ts
     * for (const item of set) {
     *   console.log(item);
     * }
     * ```
     */
    public [Symbol.iterator](): IterableIterator<T> {
        return this._array[Symbol.iterator]();
    };

    /**
     * Фильтрует элементы коллекции через предикат.
     *
     * Не оптимизирован (O(n)), рекомендуется только для нечастых операций.
     *
     * @param fn - Функция-предикат.
     * @returns Новый массив отфильтрованных элементов.
     */
    public filter(fn: (item: T) => boolean): T[] {
        return this._array.filter(fn);
    };

    /**
     * Находит первый элемент, удовлетворяющий предикату.
     *
     * Не оптимизирован (O(n)), рекомендуется только для нечастых операций.
     *
     * @param fn - Функция-предикат.
     * @returns Найденный элемент или `undefined`.
     */
    public find(fn: (item: T) => boolean): T | undefined {
        return this._array.find(fn);
    };

    /**
     * Сортирует элементы коллекции на месте и возвращает ссылку на неё же.
     *
     * Использует встроенную сортировку массива (O(n log n)).
     * После сортировки **обновляет `_indexMap`**, чтобы индексы оставались
     * корректными.
     *
     * @param fn - Компаратор (как у `Array.prototype.sort`).
     * @returns Отсортированный внутренний массив (не копия).
     */
    public sort(fn: (a: T, b: T) => number): T[] {
        // Сортируем массив на месте.
        this._array.sort(fn);

        // Перестраиваем отображение элемент -> индекс.
        this._indexMap.clear();
        for (let i = 0; i < this._array.length; i++) {
            this._indexMap.set(this._array[i], i);
        }
        return this._array;
    };

    /**
     * Полностью очищает коллекцию.
     *
     * Вместо создания нового массива обнуляет свойство `length`, что
     * снижает нагрузку на сборщик мусора (GC) при частых очистках.
     * Сложность O(1).
     */
    public clear(): void {
        this._array.length = 0;
        this._indexMap.clear();
    };

    /**
     * Количество элементов в коллекции.
     *
     * @returns Текущий размер коллекции.
     */
    public get size(): number {
        return this._array.length;
    };
}