/**
 * Структура, представляющая движок аудио-буфера.
 * Хранит пакеты аудиоданных (например, кадры Opus) в виде очереди.
 * Позволяет добавлять, читать и просматривать пакеты, отслеживать позицию чтения.
 */
export interface iAudioEngine {
    /**
     * @description Возвращает текущее количество пакетов в буфере.
     * @public
     */
    get size(): number;

    /**
     * @description Возвращает текущую позицию чтения (количество извлечённых пакетов).
     * @public
     */
    get position(): number;

    /**
     * @description Устанавливает позицию чтения вручную (может использоваться для перемотки).
     * @public
     */
    set position(pos: number);

    /**
     * Создаёт новый экземпляр AudioEngine.
     *
     * # Аргументы
     * * `max_minutes` – максимальное количество минут аудио, которое может храниться в буфере.
     *
     * # Расчёт ёмкости
     * Исход из того, что в секунду передаётся 50 пакетов (например, для 20 мс кадров Opus).
     * Ёмкость = 50 пакетов/сек * 60 сек * max_minutes.
     * Минимальная ёмкость – 1000 пакетов.
     */
    constructor(maxMinutes: number): void;

    /**
     * Запускает FFmpeg и фоновый парсинг Ogg Opus.
     *
     * # Аргументы
     * * `args` — аргументы командной строки для FFmpeg (после автоматически добавленных настроек).
     * * `ffmpeg_path` — путь к исполняемому файлу FFmpeg.
     *
     * # Автоматические аргументы
     * Метод добавляет следующие флаги для ускорения и стабильности:
     * - `-analyzeduration 0` и `-probesize 128` — минимальный анализ для быстрого старта.
     * - `-vn` — отключение видео.
     * - `-loglevel error` — только ошибки.
     * - `-nostdin` — предотвращает случайное ожидание ввода.
     *
     * # Ошибки
     * Возвращает `Error`, если FFmpeg не удалось запустить или не удалось получить `stdout`.
     * Повторный вызов `start` на уже работающем движке вызовет ошибку.
     */
    start(args: Array<string>, ffmpegPath: string): void;

    /**
     * Проверяет, можно ли "слать" аудио в буфер.
     * Возвращает true, если текущая нагрузка позволяет добавить данные без немедленного удаления старых.
     * По сути, это проверка: "есть ли свободное место?".
     */
    canAccept(): boolean;

    /**
     * Добавляет несколько пакетов в очередь.
     *
     * # Аргументы
     * * `packets` – массив бинарных буферов (из Node.js)
     */
    addPackets(packets: Array<Buffer>): void;

    /**
     * Получает несколько пакетов подряд (удаляя их) и увеличивает позицию на соответствующее количество.
     *
     * # Аргументы
     * * `count` – максимальное количество пакетов для получения.
     *
     * # Возвращает
     * Вектор Buffer (может быть меньше запрошенного, если пакетов недостаточно).
     */
    getPackets(count: number): Array<Buffer>;

    /**
     * Уничтожает движок: останавливает поток чтения, убивает ffmpeg,
     * очищает буфер. Идемпотентный.
     */
    destroy(): void;
}

/**
 * Буферизованный UDP-сокет, доступный из JavaScript через N-API.
 *
 * Предоставляет методы для отправки дейтаграмм (с буферизацией), получения входящих
 * пакетов через вызов, а также статистику. Интегрируется с глобальным балансировщиком
 * CycleManager для регулярного вызова tick(), который отправляет накопленные пакеты.
 *
 * Конструктор создаёт сокет, привязывается к случайному порту, подключается к указанному
 * удалённому адресу и регистрирует себя в глобальном балансировщике для автоматической
 * отправки.
 */
export interface iUDPSocket {
    /**
     * @description Текущее количество пакетов в очереди на отправку.
     * @public
     */
    get packets(): number;

    /**
     * @description Количество пакетов, сброшенных из-за переполнения очереди или временных ошибок.
     * @public
     */
    get drops(): number;

    /**
     * Создаёт новый UDP-сокет, подключается к указанному удалённому адресу и
     * регистрируется в глобальном балансировщике.
     *
     * # Аргументы
     * * `remote_addr` - адрес удалённого хоста в формате "address:port" (например, "127.0.0.1:12345").
     *
     * Сокет создаётся с неблокирующим режимом (set_nonblocking(true)), чтобы операции
     * send/recv не блокировали поток.
     */
    constructor(remoteAddr: string): void;

    /**
     * Инициализирует RTP-шифр с новым SSRC и ключом.
     * Безопасен для повторного вызова при реконнекте.
     *
     * # Аргументы
     * * `ssrc` — идентификатор источника синхронизации.
     * * `key` — 32-байтовый ключ AES-256-GCM.
     */
    initialize_rtp(ssrc: number, key: Array<number>): void;

    /**
     * Формирует discovery-пакет для голосового соединения Discord и возвращает его
     * в виде массива из одного элемента (`Buffer[]`).
     *
     * Discovery-пакет используется на начальном этапе установки голосового UDP-соединения
     * и имеет фиксированный размер 74 байта. Структура пакета:
     *
     * | Смещение | Размер (байт) | Описание                          |
     * |----------|---------------|-----------------------------------|
     * | 0..2     | 2             | Тип пакета (0x0001, big-endian)   |
     * | 2..4     | 2             | Длина пакета (0x0046 = 70, big-endian) |
     * | 4..8     | 4             | SSRC источника (big-endian)       |
     * | 8..74    | 66            | Заполнитель (нули)                |
     *
     * # Аргументы
     * - `ssrc` — 32-битный идентификатор источника синхронизации, уникальный для данного
     *   голосового потока.
     *
     * # Возвращаемое значение
     * `Vec<Buffer>` длины 1, содержащий сформированный discovery-пакет.
     * Возврат вектора (а не одиночного `Buffer`) обеспечивает единообразие API
     * с другими методами, возвращающими массивы пакетов (например, `packets`).
     */
    discovery(ssrc: number): void;

    /**
     * Добавляет пакет в очередь на отправку. С проверкой мусора
     *
     * # Аргументы
     * * `packet` - Buffer с данными для отправки.
     *
     * Если длина пакета будет равна 3, он будет проверен, допустим ли он!
     * Если размер пакета более 3, то позволяем ему отправится в циклической системе
     */
    pushPacket(packet: Buffer): void;

    /**
     * Добавляет пакеты в очередь на отправку. С проверкой мусора
     *
     * # Аргументы
     * * `packets` - Массив Buffer с данными для отправки.
     *
     * Если длина пакета будет равна 3, он будет проверен, допустим ли он!
     * Если размер пакета более 3, то позволяем ему отправится в циклической системе
     */
    pushPackets(packets: Array<Buffer>): void;

    /**
     * Начинает прослушивание входящих пакетов в отдельном потоке.
     *
     * # Аргументы
     * * `callback` - JS-функция, которая будет вызываться при получении каждого пакета.
     *   Функция получает один аргумент — Buffer с данными.
     *
     * Если прослушивание уже активно, метод ничего не делает.
     * Поток работает, пока не будет вызван `stop_listening` или уничтожен объект.
     * Для вызова из фонового потока используется ThreadsafeFunction.
     * @public
     */
    startListening(callback: (message: Buffer) => void): void;

    /**
     * @description Останавливает прослушивание входящих пакетов и дожидается завершения потока.
     * @public
     */
    stopListening(): void;

    /**
     * Полностью уничтожает сессию: останавливает прослушивание, очищает очередь,
     * удаляет себя из глобального балансировщика. Повторные вызовы игнорируются.
     * @public
     */
    destroy(): void;
}

/**
 * DAVESession — основная сессия для протокола MLS (Messaging Layer Security), используемая в Discord для E2EE.
 * Предоставляет методы для управления групповыми ключами, шифрования/расшифрования аудио пакетов (Opus/Video) и обработки proposals.
 *
 * @remarks
 * - Сессия инициализируется с версией протокола, ID пользователя, ID канала и опциональной парой ключей подписи.
 * - После инициализации может быть получен KeyPackage для отправки другим участникам.
 * - Для работы необходимо вызвать `setExternalSender` и обработать proposals/commit/welcome.
 * - Поддерживается режим passthrough (прозрачный пропуск пакетов) с опциональным тайм-аутом.
 * - Ведётся статистика шифрования/расшифрования.
 *
 * @see https://github.com/discord/dave
 */
export interface iDAVESession {
    /** Возвращает текущую версию протокола, установленную в сессии. */
    get protocolVersion(): number;

    /**
     * Возвращает `true`, если сессия готова к шифрованию/дешифрованию
     * (завершён обмен ключами).
     */
    get ready(): boolean;

    /**
     * Возвращает статус сессии в виде числа (0..255).
     *
     * Конкретные значения определяются внутренним перечислением `davey::Status`.
     */
    get status(): number;

    /**
     * Создаёт новую сессию DAVE.
     *
     * Параметры:
     * - `protocol_version` — ненулевая версия протокола.
     * - `user_id` — строковый идентификатор пользователя (конвертируется в u64).
     * - `channel_id` — строковый идентификатор канала (конвертируется в u64).
     * - `key_pair` — опциональная подписывающая ключевая пара.
     *
     * Возвращает ошибку, если идентификаторы не парсятся или версия протокола равна 0.
     */
    constructor(protocolVersion: number, userId: string, channelId: string, keyPair?: SigningKeyPair | undefined | null): void;

    /**
     * Переинициализирует сессию с новыми параметрами.
     *
     * Аналогичен конструктору, но применяется к уже существующему объекту,
     * сбрасывая внутреннее состояние и устанавливая новые значения.
     *
     * Параметры такие же, как у `new`.
     */
    reinit(protocolVersion: number, userId: string, channelId: string, keyPair?: SigningKeyPair | undefined | null): void;

    /**
     * Полностью сбрасывает внутреннее состояние сессии.
     *
     * После вызова сессия теряет все ключи и настройки, её можно заново инициализировать.
     */
    reset(): void;

    /**
     * Генерирует и возвращает сериализованный ключевой пакет (KeyPackage)
     * для отправки другим участникам.
     */
    getSerializedKeyPackage(): Buffer;

    /**
     * Устанавливает внешний отправляющий ключ (External Sender).
     *
     * Принимает буфер с сериализованными данными внешнего отправителя.
     */
    setExternalSender(data: Buffer): void;

    /**
     * Включает или выключает сквозной (passthrough) режим.
     *
     * В сквозном режиме медиаданные передаются без шифрования/дешифрования.
     * `expiry` — опциональное время истечения режима в секундах.
     */
    setPassthroughMode(enabled: boolean, expiry?: number | undefined | null): void;

    /**
     * Обрабатывает предложения (Proposals) от других участников.
     *
     * Параметры:
     * - `operation_type` — тип операции (u8, должно быть ≤ 10).
     * - `proposals` — буфер с сериализованными предложениями.
     * - `recognized_user_ids` — опциональный список строковых идентификаторов
     *   пользователей, чьи ключи уже известны.
     *
     * Возвращает `ProposalsResult` с опциональными `commit` и `welcome`.
     */
    processProposals(operationType: number, proposals: Buffer, recognizedUserIds?: readonly string[] | undefined | null): ProposalsResult;

    /**
     * Обрабатывает подтверждение (Commit).
     *
     * Возвращает `true` при успешной обработке.
     */
    processCommit(commit: Buffer): boolean;

    /** Обрабатывает приветственное сообщение (Welcome). */
    processWelcome(welcome: Buffer): void;

    /**
     * Оптимизированное шифрование Opus-пакета.
     *
     * Если пакет короткий (≤ 3 байта) или шифрование не удалось,
     * возвращает оригинальный пакет без изменений.
     *
     * Возвращает `Option<Buffer>`: `Some(зашифрованный или оригинальный пакет)`,
     * `None` только при невозможности шифрования (не используется в текущей реализации,
     * всегда `Some`).
     */
    encryptOpus(packet: Buffer): Buffer | null;

    /**
     * Пакетное шифрование Opus-пакетов.
     *
     * Принимает вектор буферов, возвращает вектор результатов той же длины.
     * Каждый элемент: `Some(зашифрованный или оригинальный пакет)`, либо `None`,
     * если шифрование не удалось (для пакетов длиной > 3, где произошла ошибка).
     */
    encryptOpusBatch(packets: Array<Buffer>): Array<Buffer | undefined | null>;

    /**
     * Упрощённый метод дешифрования Opus-пакетов (только аудио).
     *
     * Принимает `user_id` и зашифрованный буфер, возвращает расшифрованный Opus-пакет.
     */
    decryptOpus(userId: string, packet: Buffer): Buffer;

    /**
     * Очищает внутреннее состояние сессии (вызывает `reset`).
     *
     * Используется в деструкторе и может вызываться вручную.
     */
    cleanup(): void;
}

/**
 * Результат обработки proposals.
 * Содержит commit, который необходимо применить, и опциональный welcome для новых участников.
 */
export interface ProposalsResult {
    /** Commit-данные (всегда присутствуют при успешной обработке). */
    commit?: Buffer;

    /** Welcome-данные (требуются, если в группу добавляются новые участники). */
    welcome?: Buffer;
}

/**
 * Пара ключей подписи (асимметричная криптография).
 * Используется для аутентификации участников группы.
 */
export interface SigningKeyPair {
    /** Приватный ключ (должен храниться в секрете). */
    private: Buffer;

    /** Публичный ключ (распространяется открыто). */
    public: Buffer;
}

