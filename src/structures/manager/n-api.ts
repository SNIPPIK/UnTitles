/**
 * Структура, представляющая движок аудио-буфера.
 * Хранит пакеты аудиоданных (например, кадры Opus) в виде очереди.
 * Позволяет добавлять, читать и просматривать пакеты, отслеживать позицию чтения.
 */
export interface iAudioEngine {
    /**
     * @description Возвращает текущее количество пакетов в буфере.
     * @public
     */
    get size(): number;

    /**
     * @description Возвращает текущую позицию чтения (количество извлечённых пакетов).
     * @public
     */
    get position(): number;

    /**
     * @description Устанавливает позицию чтения вручную (может использоваться для перемотки).
     * @public
     */
    set position(pos: number);

    get readable(): boolean;

    /**
     * Создаёт новый экземпляр AudioEngine.
     *
     * # Аргументы
     * * `max_minutes` – максимальное количество минут аудио, которое может храниться в буфере.
     *
     * # Расчёт ёмкости
     * Исход из того, что в секунду передаётся 50 пакетов (например, для 20 мс кадров Opus).
     * Ёмкость = 50 пакетов/сек * 60 сек * max_minutes.
     * Минимальная ёмкость – 1000 пакетов.
     */
    constructor(maxMinutes: number): void;

    /**
     * Запускает FFmpeg и фоновый парсинг Ogg Opus.
     *
     * # Аргументы
     * * `args` — аргументы командной строки для FFmpeg (после автоматически добавленных настроек).
     * * `ffmpeg_path` — путь к исполняемому файлу FFmpeg.
     *
     * # Автоматические аргументы
     * Метод добавляет следующие флаги для ускорения и стабильности:
     * - `-analyzeduration 0` и `-probesize 128` — минимальный анализ для быстрого старта.
     * - `-vn` — отключение видео.
     * - `-loglevel error` — только ошибки.
     * - `-nostdin` — предотвращает случайное ожидание ввода.
     *
     * # Ошибки
     * Возвращает `Error`, если FFmpeg не удалось запустить или не удалось получить `stdout`.
     * Повторный вызов `start` на уже работающем движке вызовет ошибку.
     */
    start(args: Array<string>, ffmpegPath: string): void;

    /**
     * Проверяет, можно ли "слать" аудио в буфер.
     * Возвращает true, если текущая нагрузка позволяет добавить данные без немедленного удаления старых.
     * По сути, это проверка: "есть ли свободное место?".
     */
    canAccept(): boolean;

    /**
     * Добавляет несколько пакетов в очередь.
     *
     * # Аргументы
     * * `packets` – массив бинарных буферов (из Node.js)
     */
    addPackets(packets: Array<Buffer>): void;

    /**
     * Получает несколько пакетов подряд (удаляя их) и увеличивает позицию на соответствующее количество.
     *
     * # Аргументы
     * * `count` – максимальное количество пакетов для получения.
     *
     * # Возвращает
     * Вектор Buffer (может быть меньше запрошенного, если пакетов недостаточно).
     */
    getPackets(count: number): Array<Buffer>;

    /**
     * Уничтожает движок: останавливает поток чтения, убивает ffmpeg,
     * очищает буфер. Идемпотентный.
     */
    destroy(): void;
}

/**
 * Буферизованный UDP-сокет, доступный из JavaScript через N-API.
 *
 * Предоставляет методы для отправки дейтаграмм (с буферизацией), получения входящих
 * пакетов через вызов, а также статистику. Интегрируется с глобальным балансировщиком
 * CycleManager для регулярного вызова tick(), который отправляет накопленные пакеты.
 *
 * Конструктор создаёт сокет, привязывается к случайному порту, подключается к указанному
 * удалённому адресу и регистрирует себя в глобальном балансировщике для автоматической
 * отправки.
 */
export interface iUDPSocket {
    /**
     * @description Текущее количество пакетов в очереди на отправку.
     * @public
     */
    get packets(): number;

    /**
     * @description Количество пакетов, сброшенных из-за переполнения очереди или временных ошибок.
     * @public
     */
    get drops(): number;

    /**
     * Создаёт новый UDP-сокет, подключается к указанному удалённому адресу и
     * регистрируется в глобальном балансировщике.
     *
     * # Аргументы
     * * `remote_addr` - адрес удалённого хоста в формате "address:port" (например, "127.0.0.1:12345").
     *
     * Сокет создаётся с неблокирующим режимом (set_nonblocking(true)), чтобы операции
     * send/recv не блокировали поток.
     */
    constructor(remoteAddr: string): void;

    /**
     * Инициализирует RTP-шифр с новым SSRC и ключом.
     * Безопасен для повторного вызова при реконнекте.
     *
     * # Аргументы
     * * `ssrc` — идентификатор источника синхронизации.
     * * `key` — 32-байтовый ключ AES-256-GCM.
     */
    initialize_rtp(ssrc: number, key: Array<number>): void;

    /**
     * Формирует discovery-пакет для голосового соединения Discord и возвращает его
     * в виде массива из одного элемента (`Buffer[]`).
     *
     * Discovery-пакет используется на начальном этапе установки голосового UDP-соединения
     * и имеет фиксированный размер 74 байта. Структура пакета:
     *
     * | Смещение | Размер (байт) | Описание                          |
     * |----------|---------------|-----------------------------------|
     * | 0..2     | 2             | Тип пакета (0x0001, big-endian)   |
     * | 2..4     | 2             | Длина пакета (0x0046 = 70, big-endian) |
     * | 4..8     | 4             | SSRC источника (big-endian)       |
     * | 8..74    | 66            | Заполнитель (нули)                |
     *
     * # Аргументы
     * - `ssrc` — 32-битный идентификатор источника синхронизации, уникальный для данного
     *   голосового потока.
     *
     * # Возвращаемое значение
     * `Vec<Buffer>` длины 1, содержащий сформированный discovery-пакет.
     * Возврат вектора (а не одиночного `Buffer`) обеспечивает единообразие API
     * с другими методами, возвращающими массивы пакетов (например, `packets`).
     */
    discovery(ssrc: number): void;

    /**
     * Добавляет пакет в очередь на отправку. С проверкой мусора
     *
     * # Аргументы
     * * `packet` - Buffer с данными для отправки.
     *
     * Если длина пакета будет равна 3, он будет проверен, допустим ли он!
     * Если размер пакета более 3, то позволяем ему отправится в циклической системе
     */
    pushPacket(packet: Buffer): void;

    /**
     * Добавляет пакеты в очередь на отправку. С проверкой мусора
     *
     * # Аргументы
     * * `packets` - Массив Buffer с данными для отправки.
     *
     * Если длина пакета будет равна 3, он будет проверен, допустим ли он!
     * Если размер пакета более 3, то позволяем ему отправится в циклической системе
     */
    pushPackets(packets: Array<Buffer>): void;

    /**
     * Начинает прослушивание входящих пакетов в отдельном потоке.
     *
     * # Аргументы
     * * `callback` - JS-функция, которая будет вызываться при получении каждого пакета.
     *   Функция получает один аргумент — Buffer с данными.
     *
     * Если прослушивание уже активно, метод ничего не делает.
     * Поток работает, пока не будет вызван `stop_listening` или уничтожен объект.
     * Для вызова из фонового потока используется ThreadsafeFunction.
     * @public
     */
    startListening(callback: (message: Buffer) => void): void;

    /**
     * @description Останавливает прослушивание входящих пакетов и дожидается завершения потока.
     * @public
     */
    stopListening(): void;

    /**
     * Полностью уничтожает сессию: останавливает прослушивание, очищает очередь,
     * удаляет себя из глобального балансировщика. Повторные вызовы игнорируются.
     * @public
     */
    destroy(): void;
}

/**
 * DAVESession — основная сессия для протокола MLS (Messaging Layer Security), используемая в Discord для E2EE.
 * Предоставляет методы для управления групповыми ключами, шифрования/расшифрования аудио пакетов (Opus/Video) и обработки proposals.
 *
 * @remarks
 * - Сессия инициализируется с версией протокола, ID пользователя, ID канала и опциональной парой ключей подписи.
 * - После инициализации может быть получен KeyPackage для отправки другим участникам.
 * - Для работы необходимо вызвать `setExternalSender` и обработать proposals/commit/welcome.
 * - Поддерживается режим passthrough (прозрачный пропуск пакетов) с опциональным тайм-аутом.
 * - Ведётся статистика шифрования/расшифрования.
 *
 * @see https://github.com/discord/dave
 */
export interface iMLSSession {
    /**
     * Создаёт обёртку без нативной сессии.
     *
     * # Аргументы
     * * `version` — начальная версия протокола.
     * * `user_id` — идентификатор пользователя.
     * * `channel_id` — идентификатор канала.
     */
    constructor(version: number, userId: string, channelId: string): void;

    /**
     * `true`, если сессия уничтожена.
     *
     * Устанавливается в `destroy()` и остаётся `true` до конца жизни объекта.
     */
    get destroyed(): boolean;

    /**
     * `true`, если сессия повторно инициализируется.
     *
     * Устанавливается при `recoverFromInvalidTransition` или первой ошибке
     * обработки commit/welcome. Сбрасывается после успешного завершения
     * перехода с `transition_id == 0`.
     */
    get reinitializing(): boolean;

    /**
     * `true`, если в данный момент выполняется переход.
     *
     * Используется как защита от повторного входа в `execute_transition`
     * и от параллельного шифрования во время смены версии протокола.
     */
    get isTransitioning(): boolean;

    /**
     * Идентификатор последнего успешно выполненного перехода.
     *
     * `None`, если переходов ещё не было или сессия была уничтожена.
     */
    get lastTransitionId(): number | null;

    /**
     * `true`, если нативная сессия готова к шифрованию.
     *
     * `false`, если нативная сессия ещё не создана или не завершила обмен ключами.
     */
    get ready(): boolean;

    /**
     * Внутренний статус нативной сессии.
     *
     * `None`, если нативная сессия ещё не создана. Значения соответствуют
     * внутреннему перечислению `davey::Status`.
     */
    get status(): number | null;

    /**
     * Версия протокола активной нативной сессии.
     *
     * Возвращает 0, если нативная сессия ещё не создана. Не путать
     * с полем `self.version`, которое хранит запрошенную версию и может
     * отличаться от фактической версии нативной сессии.
     */
    get protocolVersion(): number;

    /**
     * Устанавливает внешнего отправителя.
     *
     * Если нативная сессия уже создана — передаёт значение напрямую,
     * иначе откладывает до момента инициализации.
     */
    set externalSender(data: Buffer);

    /**
     * Обрабатывает данные подготовки эпохи.
     *
     * Реагирует только на эпоху 1; остальные случаи игнорируются.
     * Обновляет версию протокола и запускает `reinit`.
     *
     * # Аргументы
     * * `epoch` — номер эпохи.
     * * `protocol_version` — версия протокола для этой эпохи.
     *
     * # Возвращаемое значение
     * Новый key-package, если он был создан.
     */
    prepareEpoch(epoch: number, protocolVersion: number): Buffer | null;

    /**
     * Запускает восстановление после невалидного перехода.
     *
     * Устанавливает флаг `reinitializing`, очищает ожидающие переходы
     * и выполняет `reinit_internal`.
     *
     * # Аргументы
     * * `transition_id` — идентификатор невалидного перехода.
     *
     * # Возвращаемое значение
     * Новый key-package, если он был создан.
     */
    recoverFromInvalidTransition(transitionId: number): Buffer | null;

    /**
     * Повторна инициализирует нативную сессию с текущей версией протокола.
     *
     * # Возвращаемое значение
     * Новый key-package, если он был создан.
     */
    reinit(): Buffer | null;

    /** Сбрасывает состояние нативной сессии без её уничтожения. */
    reset(): void;

    /**
     * Полностью уничтожает сессию и освобождает ресурсы.
     * Идемпотентен: повторный вызов не выполняет действий.
     */
    destroy(): void;

    /**
     * Включает или выключает passthrough-режим.
     *
     * В passthrough медиа-пакеты передаются без шифрования/расшифровки.
     *
     * # Аргументы
     * * `enabled` — `true` для включения.
     * * `expiry` — время жизни режима в секундах (опционально).
     */
    setPassthroughMode(enabled: boolean, expiry?: number | undefined | null): void;

    /**
     * Возвращает сериализованный key-package.
     *
     * # Ошибки
     * Возвращает ошибку, если нативная сессия ещё не создана.
     */
    getSerializedKeyPackage(): Buffer;

    /**
     * Обрабатывает proposals от другого участника.
     *
     * # Аргументы
     * * `operation_type` — тип операции (0 или 1).
     * * `proposals` — сериализованные предложения.
     * * `recognized_user_ids` — известные идентификаторы пользователей.
     *
     * # Возвращаемое значение
     * `ProposalsResult` с commit и welcome (если есть).
     */
    processProposals(operationType: number, proposals: Buffer, recognizedUserIds?: Array<string> | undefined | null): ProposalsResult;

    /**
     * Обрабатывает commit от другого участника.
     *
     * Первые два байта payload — `transition_id`.
     *
     * # Аргументы
     * * `payload` — сериализованные данные commit.
     *
     * # Возвращаемое значение
     * `TransitionResult` с `transition_id`, флагом успеха и признаком
     * невалидности (для инициирования повторной инициализации).
     */
    processCommit(payload: Buffer): TransitionResult;

    /**
     * Обрабатывает welcome от другого участника.
     *
     * Логика аналогична `process_commit`, но применяется к данным
     * приветственного сообщения.
     *
     * # Аргументы
     * * `payload` — сериализованные данные welcome.
     */
    processWelcome(payload: Buffer): TransitionResult;

    /**
     * Регистрирует ожидаемый переход.
     *
     * Для `transition_id == 0` переход выполняется немедленно. Для
     * `protocol_version == 0` включается passthrough с увеличенным сроком
     * (ожидание подтверждения понижения).
     *
     * # Аргументы
     * * `transition_id` — идентификатор перехода.
     * * `protocol_version` — целевая версия протокола.
     *
     * # Возвращаемое значение
     * `true`, если переход требует вызова `execute_transition`.
     */
    prepareTransition(transitionId: number, protocolVersion: number): boolean;

    /**
     * Выполняет ранее зарегистрированный переход.
     *
     * # Аргументы
     * * `transition_id` — идентификатор перехода.
     *
     * # Возвращаемое значение
     * `true`, если переход выполнен; `false`, если запись отсутствует
     * или уже выполняется другой переход.
     */
    executeTransition(transitionId: number): boolean;

    /**
     * Шифрует массив Opus-пакетов.
     *
     * Возвращает `None`, если шифрование невозможно: версия 0, идёт
     * переход, идёт повторная инициализация, сессия не готова, либо один из
     * пакетов не удалось зашифровать (batch считается неуспешным целиком).
     *
     * # Аргументы
     * * `packets` — исходные Opus-пакеты.
     *
     * # Возвращаемое значение
     * Вектор зашифрованных пакетов или `None`.
     */
    encrypt(packets: Array<Buffer>): Array<Buffer> | null;
}

/**
 * Результат обработки proposals: commit и опциональный welcome.
 *
 * Возвращается из `process_proposals`. Поле `commit` присутствует, если
 * нативная сессия сформировала новый commit для группы; `welcome` — только
 * если в группу добавляются новые участники и им нужно приглашение.
 */
export interface ProposalsResult {
    /** Данные commit. `None`, если commit не требуется. */
    commit?: Buffer
    /** Данные welcome. `None`, если новых участников нет. */
    welcome?: Buffer
}

/**
 * Результат обработки commit или welcome.
 *
 * Возвращается из `process_commit` и `process_welcome`.
 */
export interface TransitionResult {
    /** Идентификатор перехода (первые 2 байта payload). */
    transition_id: number
    /** `true`, если обработка завершилась успешно. */
    success: boolean
    /**
     * `true`, если переход признан невалидным и требует повторной инициализации.
     * Устанавливается только при первой ошибке; повторные ошибки во время
     * уже начатой повторной инициализации сигнал не выставляют.
     */
    invalidated: boolean
}


/**
 * Обёртка Voice WebSocket для JavaScript.
 *
 * Управляет подключением к Discord Voice Gateway, отправкой/приёмом
 * сообщений и эмиссией событий в JS через threadsafe-функции.
 * Вся работа с сетью и таймерами выполняется в Tokio-runtime, JS-сторона
 * получает только события и управляет жизненным циклом.
 */
export interface iVoiceWebSocket {
    /** Создаёт объект без активного подключения. */
    constructor(): void;

    /** `true`, если WebSocket-соединение активно. */
    get ready(): boolean;

    /** Текущий статус соединения (код из `ws_status`). */
    get status(): number;

    /** Последний полученный seq от Discord (для Resume). */
    get sequence(): number;

    /**
     * Регистрирует обработчик JS-события.
     *
     * Внутри создаётся threadsafe-функция, которая при срабатывании
     * преобразует `EmitData` в набор JSON-значений и передаёт их
     * JS-функции как позиционные аргументы.
     *
     * Формат аргументов зависит от имени события:
     * * `open` | `resumed` | `disconnect` — без аргументов;
     * * `info` — строка;
     * * `error` — объект `{ message, stack }`;
     * * `close` — `(code: number, reason: string)`;
     * * `binary` — `{ op, payload: number[] }`;
     * * прочие события — разобранным JSON-payload.
     *
     * # Аргументы
     * * `event` — имя события.
     * * `callback` — JS-функция-обработчик.
     *
     * # Ошибки
     * Возвращает ошибку, если не удалось построить threadsafe-функцию.
     */
    on(event: string, callback: Function): void;

    /**
     * Отправляет пакет в WebSocket.
     *
     * Если соединение ещё не готово, пакет помещается в очередь
     * и будет отправлен после установления соединения.
     *
     * # Аргументы
     * * `payload` — `Buffer` (бинарный) или `String` (текстовый).
     */
    set packet(payload: Buffer | string);

    /**
     * Открывает WebSocket-подключение к указанному endpoint'у.
     *
     * Нормализует переданный адрес: убирает схему (`ws://`, `wss://`)
     * и ведущий `/`, после чего формирует итоговый URL с `/?v=8` —
     * так Discord ожидает на голосовом шлюзе.
     *
     * # Аргументы
     * * `endpoint` — адрес шлюза (может содержать схему или нет).
     * * `_code` — необязательный код переподключения (не используется).
     */
    connect(endpoint: string, code?: number | undefined | null): void;

    /**
     * Сбрасывает текущее соединение и очищает ресурсы.
     *
     * Прерывает runtime-задачу, останавливает heartbeat, закрывает канал
     * отправки, очищает очередь и приводит флаги к состоянию "отключено".
     * Безопасен для повторного вызова.
     */
    reset(): void;

    /**
     * Полностью уничтожает объект WebSocket.
     *
     * Помимо `reset` очищает зарегистрированные события и сбрасывает
     * sequence в -1. Повторное использование после вызова невозможно.
     */
    destroy(): void;

    /**
     * Устанавливает пакет для отправки.
     *
     * Синоним для `send_packet`, используется там, где ожидается
     * setter-семантика (например, при `ws.packet = value`).
     */
    setPacket(payload: Buffer | string): void;
}

